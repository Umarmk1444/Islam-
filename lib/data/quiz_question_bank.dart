  /// Get verified questions filtered by category and difficulty
  static List<QuizQuestion> getQuestions({
    String category = 'all',
    int? difficulty,
    int limit = 15,
  }) {
    var pool = verifiedQuestions;

    if (category != 'all') {
      pool = pool.where((q) => q.category == category).toList();
    }

    if (difficulty != null) {
      final diffPool = pool.where((q) => q.difficulty == difficulty).toList();
      if (diffPool.isNotEmpty) {
        pool = diffPool;
      }
    }

    final shuffled = List<QuizQuestion>.from(pool)..shuffle();
    if (shuffled.length > limit) {
      return shuffled.sublist(0, limit);
    }
    return shuffled;
  }
