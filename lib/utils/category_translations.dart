  /// Returns natural translated title for a category given the locale.
  static String getTitle(String categoryRaw, String locale) {
    final key = categoryRaw.trim();
    final entry = _translations[key];
    if (entry != null) {
      return entry[locale] ?? entry['en'] ?? entry['ar'] ?? key;
    }
    return key;
  }

  /// Returns localized count string (e.g., '112 topics' vs '112 موضوعاً').
  static String getCountBadge(String count, String domainPart, String locale) {
    final bool isFatwa = domainPart == 'فتاوى';
    switch (locale) {
      case 'ar':
        return isFatwa ? '$count فتوى موثقة' : '$count موضوعاً';
      case 'am':
        return isFatwa ? '$count ፈትዋዎች' : '$count ርዕሶች';
      case 'om':
        return isFatwa ? 'Fatwaa $count' : 'Mata-duree $count';
      default:
        return isFatwa ? '$count verified fatawa' : '$count topics';
    }
  }
